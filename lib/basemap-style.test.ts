/**
 * THE PARCHMENT FORK. Ticket `0097`, `05-fog-of-war.md` §5.
 *
 * Every colour is resolved from the REAL `app/tokens.css`, never a hand-written palette: the
 * lightness and no-gold criteria are claims about the colours that ship.
 */
const tokensCss = readFileSync(new URL("../app/tokens.css", import.meta.url), "utf8")
const read = cssTokenReader(tokensCss)
const PALETTE = mapPaletteFrom(read)
const SOURCE = "protomaps"

type Layer = {
  id: string
  type: string
  source?: string
  minzoom?: number
  filter?: unknown
  metadata?: unknown
  paint?: Record<string, unknown>
  layout?: Record<string, unknown>
}
const styleLayers = (v: BasemapVariant) => parchmentLayers(SOURCE, v, PALETTE) as unknown as Layer[]

/** The slice of MapLibre's `Map` the insertion helpers touch, over a real layer list. */
class FakeMap {
  constructor(public layers: Layer[]) {}
  getLayer(id: string) {
    return this.layers.find((l) => l.id === id)
  }
  getStyle() {
    return { layers: this.layers }
  }
  addLayer(layer: Layer, beforeId?: string) {
    const at = beforeId ? this.layers.findIndex((l) => l.id === beforeId) : -1
    if (at === -1) this.layers.push(layer)
    else this.layers.splice(at, 0, layer)
  }
}

/** The map's full stack as the app builds it: trace web, fog, landmarks, route — in either order. */
function stack(variant: BasemapVariant, fogFirst: boolean) {
  const map = new FakeMap([...styleLayers(variant)])
  const fog = () => map.addLayer({ id: FOG_LAYER_ID, type: "custom" }, fogBeforeId(map))
  const trace = () => map.addLayer({ id: TRACE_LAYER_ID, type: "line", source: "trace-web" }, traceBeforeId(map))
  if (fogFirst) {
    fog()
    trace()
  } else {
    trace()
    fog()
  }
  map.addLayer({ id: LANDMARK_LAYER_ID, type: "symbol", source: "landmarks" }, landmarkBeforeId(map))
  map.addLayer({ id: RUN_GLOW_ID, type: "line", source: "runs" })
  return map.layers
}
const index = (layers: Layer[], id: string) => layers.findIndex((l) => l.id === id)

/** sRGB → CIELAB (D65), for the D-053 corollary. */
function lab(color: string): { L: number; C: number; sat: number; hsv: number; hsl: number } {
  const rgb = parseColor(color).map((v) => v / 255)
  const lin = rgb.map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
  const [r, g, b] = lin as [number, number, number]
  const X = (0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047
  const Y = 0.2126 * r + 0.7152 * g + 0.0722 * b
  const Z = (0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883
  const f = (t: number) => (t > 216 / 24389 ? Math.cbrt(t) : (24389 / 27 * t + 16) / 116)
  const L = 116 * f(Y) - 16
  const A = 500 * (f(X) - f(Y))
  const B = 200 * (f(Y) - f(Z))
  const C = Math.hypot(A, B)
  const max = Math.max(...rgb)
  const min = Math.min(...rgb)
  const l = (max + min) / 2
  return {
    L,
    C,
    sat: C / Math.hypot(C, L),
    hsv: max === 0 ? 0 : (max - min) / max,
    hsl: max === min ? 0 : (max - min) / (1 - Math.abs(2 * l - 1)),
  }
}

describe("criterion 1 — one source, one style module, one layer array", () => {
  it("is generated by exactly one upstream `layers()` call", () => {
    const src = readFileSync(new URL("./basemap-style.ts", import.meta.url), "utf8")
    expect(src.match(/\blayers\(source/g)).toHaveLength(1)
  })

  it("draws every basemap layer of both variants from the one source", () => {
    for (const v of BASEMAP_VARIANTS) {
      const sources = new Set(styleLayers(v).filter((l) => l.type !== "background").map((l) => l.source))
      expect([...sources]).toEqual([SOURCE])
    }
  })

  it("names one archive in the whole of lib/, components/ and app/", () => {
    const basemap = readFileSync(new URL("./basemap.ts", import.meta.url), "utf8")
    expect(basemap.match(/\.pmtiles"/g)).toHaveLength(1)
  })

  it("pins the upstream it was forked from to the installed version", () => {
    const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")) as {
      dependencies: Record<string, string>
    }
    expect(pkg.dependencies[PARCHMENT_UPSTREAM.package]).toBe(PARCHMENT_UPSTREAM.version)
  })
})

describe("criterion 2 — label density", () => {
  it("atlas renders street names down to residential at z16", () => {
    const minor = styleLayers("atlas").find((l) => l.id === "roads_labels_minor")!
    expect(minor.minzoom ?? 0).toBeLessThanOrEqual(16)
    expect(JSON.stringify(minor.filter)).toContain("minor_road")
  })

  it("atlas shows house-number labels from z16", () => {
    expect(styleLayers("atlas").find((l) => l.id === "address_label")!.minzoom).toBe(ATLAS_ADDRESS_MINZOOM)
  })

  it("adventure drops the small labels and narrows POIs to park-like kinds", () => {
    const ids = styleLayers("adventure").map((l) => l.id)
    for (const dropped of ADVENTURE_DROPPED_LAYERS) expect(ids).not.toContain(dropped)
    const pois = JSON.stringify(styleLayers("adventure").find((l) => l.id === "pois")!.filter)
    expect(pois).toContain(JSON.stringify([...ADVENTURE_POI_KINDS]))
  })

  it("adventure still renders place names, major roads and parks", () => {
    const ids = styleLayers("adventure").map((l) => l.id)
    for (const kept of ["places_locality", "places_subplace", "roads_labels_major", "roads_major", "landuse_park", "pois"]) {
      expect(ids).toContain(kept)
    }
  })
})

describe("criterion 3 — above or below the fog", () => {
  for (const fogFirst of [true, false]) {
    const order = fogFirst ? "fog added first" : "trace added first"

    it(`atlas: every label and the 0.5 road copy above the fog (${order})`, () => {
      const layers = stack("atlas", fogFirst)
      const fog = index(layers, FOG_LAYER_ID)
      const symbols = layers.filter((l) => l.type === "symbol" && l.source === SOURCE)
      const ghosts = layers.filter((l) => l.id.startsWith(ROAD_GHOST_PREFIX))
      expect(symbols.length).toBeGreaterThan(5)
      expect(ghosts.length).toBeGreaterThan(5)
      for (const l of [...symbols, ...ghosts]) expect(index(layers, l.id)).toBeGreaterThan(fog)
      for (const g of ghosts) expect(g.paint!["line-opacity"]).toBe(ATLAS_ROAD_GHOST_OPACITY)
      expect(fogSplitsBasemap(layers, SOURCE)).toBe(true)
    })

    it(`adventure: every label and road below the fog (${order})`, () => {
      const layers = stack("adventure", fogFirst)
      expect(layers.some(isAboveFogLayer)).toBe(false)
      expect(fogIsAboveAllSymbols(layers.filter((l) => l.source === SOURCE || l.id === FOG_LAYER_ID))).toBe(true)
      expect(fogSplitsBasemap(layers, SOURCE)).toBe(true)
    })

    /** D-299/D-307 as amended for atlas by the operator's 0097 call (Q1 = B). */
    it(`the trace web: above roads and below labels; above the fog in atlas only (${order})`, () => {
      for (const v of BASEMAP_VARIANTS) {
        const layers = stack(v, fogFirst)
        const trace = index(layers, TRACE_LAYER_ID)
        const firstLabel = layers.findIndex((l) => l.type === "symbol" && l.source === SOURCE)
        expect(trace).toBeLessThan(firstLabel)
        expect(trace).toBeGreaterThan(index(layers, "roads_bridges_highway"))
        if (v === "atlas") {
          expect(trace).toBeGreaterThan(index(layers, FOG_LAYER_ID))
          for (const g of layers.filter((l) => l.id.startsWith(ROAD_GHOST_PREFIX))) {
            expect(trace).toBeGreaterThan(index(layers, g.id))
          }
        } else {
          expect(trace).toBeLessThan(index(layers, FOG_LAYER_ID))
        }
      }
    })

    it(`landmarks above the fog and the route on top, in both variants (${order})`, () => {
      for (const v of BASEMAP_VARIANTS) {
        const layers = stack(v, fogFirst)
        expect(index(layers, LANDMARK_LAYER_ID)).toBeGreaterThan(index(layers, FOG_LAYER_ID))
        expect(index(layers, RUN_GLOW_ID)).toBe(layers.length - 1)
      }
    })
  }

  it("the road copies are fills only, in the fill colour — invisible over an explored road", () => {
    const layers = styleLayers("atlas")
    for (const g of layers.filter((l) => l.id.startsWith(ROAD_GHOST_PREFIX))) {
      expect(g.id).not.toMatch(/casing|tunnels|rail/)
      const original = layers.find((l) => l.id === g.id.slice(ROAD_GHOST_PREFIX.length))!
      expect(g.paint!["line-color"]).toStrictEqual(original.paint!["line-color"])
      expect(g.paint!["line-width"]).toStrictEqual(original.paint!["line-width"])
    }
  })
})

describe("criterion 4 — the D-053 corollary: light, low-chroma ground", () => {
  for (const v of BASEMAP_VARIANTS) {
    it(`${v}: ground L* >= 80 and CIELAB saturation <= 25%`, () => {
      const ground = styleLayers(v).find((l) => l.id === "background")!.paint!["background-color"] as string
      const earth = styleLayers(v).find((l) => l.id === "earth")!.paint!["fill-color"]
      expect(earth).toBe(ground)
      const m = lab(ground)
      expect(m.L).toBeGreaterThanOrEqual(80)
      expect(m.sat).toBeLessThanOrEqual(0.25)
      expect(m.hsv).toBeLessThanOrEqual(0.25)
    })
  }

  it("adventure's paper is warmer and older than atlas's, never darker than the floor", () => {
    const g = (v: BasemapVariant) =>
      lab(styleLayers(v).find((l) => l.id === "background")!.paint!["background-color"] as string)
    expect(g("adventure").L).toBeLessThan(g("atlas").L)
    expect(g("adventure").C).toBeGreaterThan(g("atlas").C)
  })
})

describe("criterion 5 — no gold anywhere in the basemap (D-148)", () => {
  const golds = ["--gold-300", "--gold-500", "--gold-700"].map((t) => parseColor(read(t)).join(","))

  it("no --map-* token points at a gold primitive", () => {
    for (const token of Object.values(MAP_TOKENS)) {
      expect(tokensCss).not.toMatch(new RegExp(`\\${token}:\\s*var\\(--gold`))
    }
  })

  it("no layer in either variant paints gold, as text or otherwise", () => {
    const colours: string[] = []
    const walk = (v: unknown) => {
      if (typeof v === "string" && /^(#|rgb)/.test(v)) colours.push(v)
      else if (Array.isArray(v)) v.forEach(walk)
      else if (v && typeof v === "object") Object.values(v).forEach(walk)
    }
    for (const v of BASEMAP_VARIANTS) for (const l of styleLayers(v)) walk(l.paint)
    expect(colours.length).toBeGreaterThan(50)
    for (const c of colours) expect(golds).not.toContain(parseColor(c).join(","))
  })
})

describe("criterion 6 — missing tiles paint flat parchment", () => {
  it("the background layer is the ground colour, so a hole in the tiles is parchment", () => {
    for (const v of BASEMAP_VARIANTS) {
      const bg = styleLayers(v)[0]!
      expect(bg.type).toBe("background")
      expect(lab(bg.paint!["background-color"] as string).L).toBeGreaterThanOrEqual(80)
    }
  })
})

