/**
 * Ticket `0195`. `05-fog-of-war.md` §2.2 steps 1-3.
 *
 * `traceToSegments` was extracted out of `traceToCells` so the drawn route and the revealed
 * ground come from one sanitation path. Two things have to stay true, and they are the whole
 * of this file: the extraction changed no cell, and the chords between segments do not exist.
 *
 * GEOMETRY IS SYNTHETIC, near Point Nemo — `08-security-privacy.md` §7.2, D-199. This
 * repository is public.
 */

const NEMO = { lat: -48.876, lng: -123.393 }
const R_EARTH = 6_371_008.8
const toRad = (d: number) => (d * Math.PI) / 180
const toDeg = (r: number) => (r * 180) / Math.PI

function step(from: { lat: number; lng: number }, metres: number, bearing: number) {
  return {
    lat: from.lat + toDeg((metres * Math.cos(bearing)) / R_EARTH),
    lng: from.lng + toDeg((metres * Math.sin(bearing)) / (R_EARTH * Math.cos(toRad(from.lat)))),
  }
}

function line(
  from: { lat: number; lng: number },
  bearing: number,
  count: number,
  spacingM: number,
  speedMs = 3,
  t0 = 0,
): GeoPoint[] {
  const out: GeoPoint[] = []
  for (let i = 0; i < count; i++) {
    const p = step(from, i * spacingM, bearing)
    out.push({ ...p, t: t0 + Math.round((i * spacingM * 1000) / speedMs) })
  }
  return out
}

function trace(points: GeoPoint[], gaps: Array<[number, number]> = []): Trace {
  const lats = points.map((p) => p.lat)
  const lngs = points.map((p) => p.lng)
  return {
    points,
    gaps,
    simplified: false,
    bbox: points.length
      ? [Math.min(...lngs), Math.min(...lats), Math.max(...lngs), Math.max(...lats)]
      : [0, 0, 0, 0],
    pointCount: points.length,
  }
}

const metres = (a: GeoPoint, b: GeoPoint): number => {
  const dLat = toRad(b.lat - a.lat)
  const dLng = toRad(b.lng - a.lng) * Math.cos(toRad((a.lat + b.lat) / 2))
  return Math.hypot(dLat, dLng) * R_EARTH
}

