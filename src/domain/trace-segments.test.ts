describe("traceToSegments — the extraction preserved traceToCells (0195 criterion 1)", () => {
  const cases: Record<string, Trace> = {
    straight: trace(line(NEMO, 0, 40, 20)),
    gapped: trace(
      [...line(NEMO, 0, 20, 20), ...line(step(NEMO, 5_000, 0), 0, 20, 20, 3, 900_000)],
      [[19, 20]],
    ),
    loop: trace([
      ...line(NEMO, 0, 25, 20),
      ...line(step(NEMO, 500, 0), Math.PI / 2, 25, 20, 3, 170_000),
      ...line(step(step(NEMO, 500, 0), 500, Math.PI / 2), Math.PI, 25, 20, 3, 340_000),
    ]),
    teleport: trace([
      ...line(NEMO, 0, 15, 20),
      ...line(step(NEMO, 30_000, Math.PI / 2), 0, 15, 20, 3, 100_000),
    ]),
  }

  for (const [name, t] of Object.entries(cases)) {
    it(`emits exactly the pre-extraction cells for ${name}`, () => {
      expect([...traceToCells(t)].sort()).toEqual(PRE_EXTRACTION[name])
    })
  }

  it("emits nothing for an empty trace, as it did before", () => {
    expect([...traceToCells(trace([]))]).toEqual([])
  })

  it("reports the same rejects through both entry points", () => {
    const t = trace(line(NEMO, 0, 30, 20))
    expect(traceToSegments(t).rejects).toEqual(traceToCells(t).rejects)
  })

  it("counts one segment per piece steps 1-3 left behind", () => {
    const t = trace(line(NEMO, 0, 30, 20))
    const { segments, rejects } = traceToSegments(t)
    expect(rejects.segments).toBe(segments.length)
  })
})

describe("traceToSegments — the joining chords never exist (0057 criterion 8)", () => {
  /**
   * THE CASE `0057` CANNOT GET WRONG. A trace split by a 15-minute gap 5 km from where it
   * resumes must not leave a 5 km edge anywhere in the output — on the map that edge is a
   * straight line across a bay, and on a map that never re-fogs (D-020) it is permanent.
   *
   * Asserted as "no edge longer than the sampling spacing allows" rather than as a segment
   * count, because a count passes if the chord is inside one of the segments.
   */
  it("splits a gapped trace and draws no edge across the gap", () => {
    const first = line(NEMO, 0, 20, 20)
    const second = line(step(NEMO, 5_000, 0), 0, 20, 20, 3, 900_000)
    const { segments } = traceToSegments(trace([...first, ...second], [[19, 20]]))

    expect(segments.length).toBeGreaterThan(1)
    for (const segment of segments) {
      for (let i = 1; i < segment.length; i++) {
        // The 5 km chord would be two orders of magnitude over the 20 m sampling step.
        expect(metres(segment[i - 1]!, segment[i]!)).toBeLessThan(200)
      }
    }
  })

  it("leaves the two pieces at their real distance from one another", () => {
    const first = line(NEMO, 0, 20, 20)
    const second = line(step(NEMO, 5_000, 0), 0, 20, 20, 3, 900_000)
    const { segments } = traceToSegments(trace([...first, ...second], [[19, 20]]))

    const last = segments[0]!.at(-1)!
    const next = segments[1]![0]!
    // The gap is REAL and stays real. A renderer draws two lines with a hole between them;
    // nothing here quietly bridges it, and nothing here pretends it was never there.
    expect(metres(last, next)).toBeGreaterThan(4_000)
  })
})
