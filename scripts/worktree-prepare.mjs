#!/usr/bin/env node
/**
 * D-312. Makes a fresh git worktree runnable: what a wave agent's worktree lacks
 * is exactly what .gitignore keeps out of git.
 *
 *   node_modules/          a HARD-LINKED copy of the main checkout's (`cp -al`, ~7 s,
 *                          no extra disk). Not a symlink: the CDK bundler in the
 *                          amplify/*.test.ts suites resolves real paths and refuses
 *                          an entry outside the project root (PathNotUnderRoot).
 *                          Hard links share bytes, so never edit a file inside
 *                          node_modules in a worktree — it edits the main one too.
 *   amplify_outputs.json   copied — generated by the backend deploy, gitignored (0004)
 *   public/maplibre/       regenerated by the prebuild step, as `npm run build` would
 *
 * Run from inside the worktree. Idempotent. Refuses to run in the main checkout,
 * which already has everything this would create.
 *
 * NOT copied: .claude/settings.json (AWS_PROFILE reaches the agent through the
 * session's environment), .env.* (none is needed locally; never copy secrets).
 */
import { execFileSync } from "node:child_process"
import { copyFileSync, existsSync, lstatSync } from "node:fs"
import { dirname, join, resolve } from "node:path"

const git = (...args) => execFileSync("git", args, { encoding: "utf8" }).trim()

const here = git("rev-parse", "--show-toplevel")
const main = dirname(resolve(here, git("rev-parse", "--git-common-dir")))
if (resolve(here) === resolve(main)) {
  console.error("worktree-prepare: this is the main checkout, not a worktree. Nothing done.")
  process.exit(1)
}

const nm = join(here, "node_modules")
if (!lstatSync(nm, { throwIfNoEntry: false })) {
  try {
    execFileSync("cp", ["-al", join(main, "node_modules"), nm])
    console.log("node_modules hard-linked from the main checkout")
  } catch {
    // Different filesystem, or no GNU cp. A symlink would break the amplify/ tests.
    console.error("worktree-prepare: could not hard-link node_modules. Run `npm install --no-save` here instead (D-162).")
    process.exit(1)
  }
}

const outputs = "amplify_outputs.json"
if (!existsSync(join(here, outputs))) {
  if (existsSync(join(main, outputs))) {
    copyFileSync(join(main, outputs), join(here, outputs))
    console.log(`${outputs} copied`)
  } else console.log(`${outputs} absent in the main checkout too — typecheck will use none`)
}

execFileSync("node", ["scripts/copy-maplibre-worker.mjs"], { cwd: here, stdio: "inherit" })
console.log(`ready: ${here}`)
